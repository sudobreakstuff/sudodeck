func pressKey(key uint16) {
	if code, ok := hidToMac[key]; ok {
		macMu.Lock()
		defer macMu.Unlock()
		C.macSendKeyDown(code)
		C.macSendKeyUp(code)
	}
}

func pressMods(mods uint8) {
	macMu.Lock()
	defer macMu.Unlock()
	for _, k := range modToHIDKeys(mods) {
		if code, ok := hidToMac[k]; ok {
			C.macSendKeyDown(code)
		}
	}
}

func releaseAll() {
	macMu.Lock()
	defer macMu.Unlock()
	mods := []uint16{0xE0, 0xE1, 0xE2, 0xE3, 0xE4, 0xE5, 0xE6, 0xE7}
	for _, k := range mods {
		if code, ok := hidToMac[k]; ok {
			C.macSendKeyUp(code)
		}
	}
	// Release all letter keys
	for hid, code := range hidToMac {
		if hid >= 0x04 && hid <= 0x38 {
			C.macSendKeyUp(code)
		}
	}
}

func injectMediaTap(key uint16) {
	// On macOS, we can use the NSEvent key codes for media
	var code C.CGKeyCode
	switch key {
	case 0xE8:
		code = 0x48 // Sound Up
	case 0xE9:
		code = 0x49 // Sound Down
	case 0xEA:
		code = 0x4A // Mute
	case 0xEB:
		code = 0x4B // Play/Pause
	case 0xEC:
		code = 0x4C // Next
	case 0xED:
		code = 0x4D // Previous
	case 0xEE:
		code = 0x4E // Stop
	default:
		return
	}
	macMu.Lock()
	defer macMu.Unlock()
	C.macSendKeyDown(code)
	C.macSendKeyUp(code)
}

